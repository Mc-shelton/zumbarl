const ITEM_MAP = new Map(MARKETPLACE_ITEMS.map((item) => [item.id, item]))

const withGalleryFallback = (item) => ({
  ...item,
  galleryImages: Array.isArray(item.galleryImages) && item.galleryImages.length > 0
    ? item.galleryImages
    : [item.image, ...DEFAULT_GALLERY_IMAGES.filter((image) => image !== item.image)].slice(0, 6),
})

export const FEATURED_ITEMS = FEATURED_ITEM_IDS.map((id) => ITEM_MAP.get(id)).filter(Boolean).map(withGalleryFallback)
export const RECENT_ITEMS = RECENT_ITEM_IDS.map((id) => ITEM_MAP.get(id)).filter(Boolean).map(withGalleryFallback)
export const TRENDING_ITEMS = TRENDING_ITEM_IDS.map((id) => ITEM_MAP.get(id)).filter(Boolean).map(withGalleryFallback)

export const ALL_MARKETPLACE_ITEMS = MARKETPLACE_ITEMS.map(withGalleryFallback)

export function getMarketplaceItemPath(itemId) {
  return `/campus/opportunities/buy-sell/${itemId}`
}

export function getMarketplaceItem(itemId) {
  const item = ITEM_MAP.get(itemId)
  return item ? withGalleryFallback(item) : null
}

export function getMarketplaceRelatedItems(itemId, limit = 5) {
  return ALL_MARKETPLACE_ITEMS.filter((item) => item.id !== itemId).slice(0, limit)
}

